from app.organization.core.domain.value_objects.member_status import MemberStatus
from app.shared.adapter.outbound.object_relational_db.objects import EnumType, Table

MEMBER_STATUS = EnumType.from_enum("member_status_t", MemberStatus)

ORGANIZATION_MEMBER = Table(
    name="organization_member",
    depends_on=("organization", "user", "member_status_t"),
    sql="""
CREATE TABLE organization_member (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint NOT NULL REFERENCES organization (id) ON DELETE RESTRICT,
    user_id          bigint NOT NULL REFERENCES "user" (id) ON DELETE RESTRICT,
    email            text,
    phone            text,
    job_title        text,
    avatar_url       text,
    status           member_status_t NOT NULL,
    joined_at        timestamptz,
    CONSTRAINT organization_member_unique UNIQUE (organization_id, user_id)
)
""",
)
