from app.shared.adapter.outbound.object_relational_db.schema.objects import Table

# A plain UNIQUE allows many NULLs, so it matches the partial unique of the relational model.
ORGANIZATION = Table(
    name="organization",
    depends_on=("json_object_d",),
    sql="""
CREATE TABLE organization (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         varchar(200) NOT NULL,
    tax_id       varchar(20),
    is_active    boolean NOT NULL,
    settings     json_object_d NOT NULL,
    created_at   timestamptz NOT NULL,
    modified_at  timestamptz NOT NULL,
    CONSTRAINT organization_tax_id_unique UNIQUE (tax_id)
)
""",
)
