from app.shared.adapter.outbound.object_relational_db.schema.objects import Table

MEMBER_GROUP = Table(
    name="member_group",
    depends_on=("organization",),
    sql="""
CREATE TABLE member_group (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint REFERENCES organization (id) ON DELETE RESTRICT,
    parent_id        bigint REFERENCES member_group (id) ON DELETE SET NULL,
    name             varchar(120) NOT NULL,
    description      text,
    created_at       timestamptz NOT NULL,
    CONSTRAINT member_group_name_unique UNIQUE (organization_id, name)
)
""",
)
