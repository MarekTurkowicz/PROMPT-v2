from typing import Protocol

from app.organization.core.domain.entities.organization import Organization


class OrganizationPort(Protocol):
    def exists_by_tax_id(self, tax_id: str) -> bool: ...
    def get_by_id(self, organization_id: int) -> Organization | None: ...
    def create_obj(self, organization_entity: Organization) -> Organization: ...
    def update_obj(self, organization_entity: Organization) -> Organization: ...
