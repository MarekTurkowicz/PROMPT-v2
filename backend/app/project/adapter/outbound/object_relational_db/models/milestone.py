from app.project.core.domain.enums.milestone_status import MilestoneStatus
from app.shared.adapter.outbound.object_relational_db.objects import EnumType, Table

MILESTONE_STATUS = EnumType.from_enum("milestone_status_t", MilestoneStatus)

MILESTONE = Table(
    name="milestone",
    depends_on=("project", "milestone_status_t", "position_d"),
    sql="""
CREATE TABLE milestone (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  bigint NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    name        text NOT NULL,
    status      milestone_status_t NOT NULL,
    due_date    date,
    position    position_d NOT NULL,
    created_at  timestamptz NOT NULL,
    updated_at  timestamptz NOT NULL
)
""",
)
