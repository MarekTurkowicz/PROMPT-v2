from app.project.core.domain.enums.status_category import StatusCategory
from app.project.core.domain.value_objects.color import Color
from app.shared.adapter.outbound.object_relational_db.objects import Domain, EnumType, Statement, Table

STATUS_CATEGORY = EnumType.from_enum("status_category_t", StatusCategory)

COLOR = Domain.from_value_object("color_d", "text", Color)

TASK_STATUS = Table(
    name="task_status",
    depends_on=("organization", "project", "status_category_t", "color_d", "position_d"),
    sql="""
CREATE TABLE task_status (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint NOT NULL REFERENCES organization (id) ON DELETE CASCADE,
    project_id       bigint REFERENCES project (id) ON DELETE CASCADE,
    category         status_category_t NOT NULL,
    name             text NOT NULL,
    color            color_d NOT NULL,
    position         position_d NOT NULL,
    is_default       boolean NOT NULL,
    is_active        boolean NOT NULL,
    CONSTRAINT task_status_name_unique UNIQUE NULLS NOT DISTINCT (organization_id, project_id, name)
)
""",
)

TASK_STATUS_ONE_DEFAULT_IN_ORG = Statement(
    name="task_status_one_default_in_org",
    depends_on=("task_status",),
    sql="""
CREATE UNIQUE INDEX task_status_one_default_in_org ON task_status (organization_id)
    WHERE is_default AND project_id IS NULL
""",
)
