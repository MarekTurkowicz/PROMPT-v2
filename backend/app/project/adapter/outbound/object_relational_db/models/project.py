from app.project.core.domain.enums.project_status import ProjectStatus
from app.shared.adapter.outbound.object_relational_db.objects import EnumType, Table

PROJECT_STATUS = EnumType.from_enum("project_status_t", ProjectStatus)

# hidden_status_ids stays a plain bigint[]: an array has no FK, the adapter checks the ids.
PROJECT = Table(
    name="project",
    depends_on=("organization", "organization_member", "project_status_t"),
    sql="""
CREATE TABLE project (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id    bigint NOT NULL REFERENCES organization (id) ON DELETE RESTRICT,
    owner_id           bigint NOT NULL REFERENCES organization_member (id) ON DELETE RESTRICT,
    name               text NOT NULL,
    description        text NOT NULL,
    status             project_status_t NOT NULL,
    start_date         date,
    end_date           date,
    hidden_status_ids  bigint[] NOT NULL,
    created_at         timestamptz NOT NULL,
    updated_at         timestamptz NOT NULL,
    CONSTRAINT project_dates_ok CHECK (start_date IS NULL OR end_date IS NULL OR end_date >= start_date)
)
""",
)
