from app.shared.adapter.outbound.object_relational_db.schema.objects import Statement, Table

PROJECT_FUNDING = Table(
    name="project_funding",
    depends_on=("project", "funding"),
    sql="""
CREATE TABLE project_funding (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id        bigint NOT NULL REFERENCES project (id) ON DELETE RESTRICT,
    funding_id        bigint NOT NULL REFERENCES funding (id) ON DELETE RESTRICT,
    allocation_start  date,
    allocation_end    date,
    is_primary        boolean NOT NULL,
    note              text NOT NULL,
    created_at        timestamptz NOT NULL,
    detached_at       timestamptz,
    CONSTRAINT project_funding_id_project UNIQUE (id, project_id),
    CONSTRAINT project_funding_dates_ok CHECK (
        allocation_start IS NULL OR allocation_end IS NULL OR allocation_end >= allocation_start
    )
)
""",
)

# Detached links are history, so both rules count only active links.
PROJECT_FUNDING_UNIQUE = Statement(
    name="project_funding_unique",
    depends_on=("project_funding",),
    sql="""
CREATE UNIQUE INDEX project_funding_unique ON project_funding (project_id, funding_id)
    WHERE detached_at IS NULL
""",
)

PROJECT_FUNDING_ONE_PRIMARY = Statement(
    name="project_funding_one_primary",
    depends_on=("project_funding",),
    sql="""
CREATE UNIQUE INDEX project_funding_one_primary ON project_funding (project_id)
    WHERE is_primary AND detached_at IS NULL
""",
)
