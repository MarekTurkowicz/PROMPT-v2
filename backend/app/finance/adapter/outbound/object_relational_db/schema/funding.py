from app.shared.adapter.outbound.object_relational_db.schema.objects import EnumType, Table

FUNDING_TYPE = EnumType(name="funding_type_t", values=("grant", "sponsorship", "donation", "internal"))

FUNDING = Table(
    name="funding",
    depends_on=("organization", "funding_type_t", "money_d"),
    sql="""
CREATE TABLE funding (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id     bigint REFERENCES organization (id) ON DELETE RESTRICT,
    type                funding_type_t NOT NULL,
    name                varchar(200) NOT NULL,
    funder              varchar(200) NOT NULL,
    program             varchar(200) NOT NULL,
    agreement_number    varchar(100) NOT NULL,
    amount_total        money_d NOT NULL,
    start_date          date,
    end_date            date,
    reporting_deadline  date,
    description         text NOT NULL,
    created_at          timestamptz NOT NULL,
    CONSTRAINT funding_dates_ok CHECK (start_date IS NULL OR end_date IS NULL OR end_date >= start_date)
)
""",
)
