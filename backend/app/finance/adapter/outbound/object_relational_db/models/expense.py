from app.finance.core.domain.enums.expense_type import ExpenseType
from app.shared.adapter.outbound.object_relational_db.objects import EnumType, Table

EXPENSE_TYPE = EnumType.from_enum("expense_type_t", ExpenseType)

EXPENSE = Table(
    name="expense",
    depends_on=(
        "project",
        "project_funding",
        "task",
        "organization_member",
        "expense_type_t",
        "money_d",
        "attachment_ids_unique",
    ),
    sql="""
CREATE TABLE expense (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id          bigint REFERENCES project (id) ON DELETE RESTRICT,
    project_funding_id  bigint REFERENCES project_funding (id) ON DELETE RESTRICT,
    task_id             bigint REFERENCES task (id) ON DELETE SET NULL,
    type                expense_type_t NOT NULL,
    amount              money_d NOT NULL,
    spent_on_date       date NOT NULL,
    document_number     text,
    description         text NOT NULL,
    attachments         attachment_d[] NOT NULL,
    created_by_id       bigint NOT NULL REFERENCES organization_member (id) ON DELETE RESTRICT,
    created_at          timestamptz NOT NULL,
    CONSTRAINT expense_one_of_project_project_funding CHECK (
        (project_id IS NOT NULL) <> (project_funding_id IS NOT NULL)
    ),
    CONSTRAINT expense_attachment_ids_unique CHECK (attachment_ids_unique(attachments))
)
""",
)
