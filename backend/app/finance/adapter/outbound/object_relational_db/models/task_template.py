from app.finance.core.domain.value_objects.due_days import DueDays
from app.shared.adapter.outbound.object_relational_db.objects import Domain, Table

DUE_DAYS = Domain.from_value_object("due_days_d", "integer", DueDays)

TASK_TEMPLATE = Table(
    name="task_template",
    depends_on=("funding", "task_status", "priority_d", "est_hours_d", "due_days_d"),
    sql="""
CREATE TABLE task_template (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    funding_id         bigint NOT NULL REFERENCES funding (id) ON DELETE CASCADE,
    title              text NOT NULL,
    description        text NOT NULL,
    default_status_id  bigint REFERENCES task_status (id) ON DELETE SET NULL,
    default_priority   priority_d NOT NULL,
    default_est_hours  est_hours_d,
    default_due_days   due_days_d,
    mandatory          boolean NOT NULL
)
""",
)
