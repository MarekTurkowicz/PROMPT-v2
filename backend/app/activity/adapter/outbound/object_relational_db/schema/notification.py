from app.shared.adapter.outbound.object_relational_db.schema.objects import Table

# activity_id is SET NULL (relational: CASCADE, MongoDB: kept): the retention job deletes old
# activity_log rows, and the notification of the user must stay.
NOTIFICATION = Table(
    name="notification",
    depends_on=("activity_log", "user", "json_object_d"),
    sql="""
CREATE TABLE notification (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id   bigint REFERENCES activity_log (id) ON DELETE SET NULL,
    recipient_id  bigint NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
    content       json_object_d NOT NULL CHECK (content <> '{}'::jsonb),
    read_at       timestamptz,
    created_at    timestamptz NOT NULL,
    CONSTRAINT notification_activity_recipient_unique UNIQUE (activity_id, recipient_id)
)
""",
)
