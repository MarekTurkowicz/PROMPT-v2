from app.activity.core.domain.enums.activity_action import ActivityAction
from app.activity.core.domain.enums.entity_type import EntityType
from app.shared.adapter.outbound.object_relational_db.objects import EnumType, Statement, Table

ENTITY_TYPE = EnumType.from_enum("entity_type_t", EntityType)

ACTIVITY_ACTION = EnumType.from_enum("activity_action_t", ActivityAction)

ACTIVITY_LOG = Table(
    name="activity_log",
    depends_on=("organization", "organization_member", "entity_type_t", "activity_action_t"),
    sql="""
CREATE TABLE activity_log (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint NOT NULL REFERENCES organization (id) ON DELETE RESTRICT,
    actor_id         bigint REFERENCES organization_member (id) ON DELETE RESTRICT,
    entity_type      entity_type_t NOT NULL,
    entity_id        bigint NOT NULL,
    action           activity_action_t NOT NULL,
    changes          jsonb NOT NULL,
    created_at       timestamptz NOT NULL
)
""",
)

ACTIVITY_LOG_GUARD = Statement(
    name="activity_log_guard",
    sql="""
CREATE FUNCTION activity_log_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' AND OLD.created_at < now() - interval '6 months' THEN RETURN OLD; END IF;
    RAISE EXCEPTION 'activity_log is append-only: % is not allowed', TG_OP;
END $$
""",
)

ACTIVITY_LOG_APPEND_ONLY = Statement(
    name="activity_log_append_only",
    depends_on=("activity_log", "activity_log_guard"),
    sql="""
CREATE TRIGGER activity_log_append_only BEFORE UPDATE OR DELETE ON activity_log
    FOR EACH ROW EXECUTE FUNCTION activity_log_guard()
""",
)

# A row trigger does not fire on TRUNCATE, so it needs its own statement trigger.
ACTIVITY_LOG_NO_TRUNCATE = Statement(
    name="activity_log_no_truncate",
    depends_on=("activity_log", "activity_log_guard"),
    sql="""
CREATE TRIGGER activity_log_no_truncate BEFORE TRUNCATE ON activity_log
    FOR EACH STATEMENT EXECUTE FUNCTION activity_log_guard()
""",
)
