from app.shared.adapter.outbound.object_relational_db.objects import Table

NOTIFICATION = Table(
    name="notification",
    depends_on=("activity_log", "user"),
    sql="""
CREATE TABLE notification (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id   bigint REFERENCES activity_log (id) ON DELETE CASCADE,
    recipient_id  bigint NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
    content       jsonb,
    read_at       timestamptz,
    created_at    timestamptz NOT NULL,
    CONSTRAINT notification_activity_recipient_unique UNIQUE (activity_id, recipient_id)
)
""",
)
