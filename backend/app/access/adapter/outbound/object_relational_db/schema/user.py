from app.shared.adapter.outbound.object_relational_db.schema.objects import Domain, Table

# Replaces the relational CHECK user_email_lowercase: Jan@x.pl and jan@x.pl are the same login.
LOGIN_EMAIL = Domain(
    name="login_email_d",
    base="email_d",
    check="VALUE = lower(VALUE)",
    depends_on=("email_d",),
)

USER = Table(
    name="user",
    depends_on=("login_email_d",),
    sql="""
CREATE TABLE "user" (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password      varchar(128) NOT NULL,
    last_login    timestamptz,
    email         login_email_d NOT NULL UNIQUE,
    first_name    varchar(150) NOT NULL,
    last_name     varchar(150) NOT NULL,
    is_active     boolean NOT NULL,
    is_staff      boolean NOT NULL,
    is_superuser  boolean NOT NULL,
    date_joined   timestamptz NOT NULL
)
""",
)
