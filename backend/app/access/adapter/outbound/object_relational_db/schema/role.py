PERMISSION_CODE = Domain(
    name="permission_code_d",
    base="varchar(60)",
    check=f"VALUE IN ({', '.join(quote_literal(code) for code in PERMISSION_CODES)})",
)

# A CHECK cannot hold a subquery, so the "no duplicates" rule lives in an IMMUTABLE function.
PERMISSION_CODES_DISTINCT = Statement(
    name="permission_codes_distinct",
    depends_on=("permission_code_d",),
    sql="""
CREATE FUNCTION permission_codes_distinct(codes permission_code_d[]) RETURNS boolean
LANGUAGE sql IMMUTABLE AS $$ SELECT count(DISTINCT c) = count(*) FROM unnest(codes) AS c $$
""",
)

PERMISSION_SET = Domain(
    name="permission_set_d",
    base="permission_code_d[]",
    check="permission_codes_distinct(VALUE)",
    depends_on=("permission_code_d", "permission_codes_distinct"),
)

ROLE = Table(
    name="role",
    depends_on=("organization", "permission_set_d"),
    sql="""
CREATE TABLE role (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint NOT NULL REFERENCES organization (id) ON DELETE CASCADE,
    name             varchar(120) NOT NULL,
    permissions      permission_set_d NOT NULL,
    CONSTRAINT role_name_unique UNIQUE (organization_id, name)
)
""",
)
