from app.shared.adapter.outbound.object_relational_db.objects import Table

# NULLS NOT DISTINCT (PostgreSQL 15+): the same role twice for the whole organization is a duplicate.
ROLE_ASSIGNMENT = Table(
    name="role_assignment",
    depends_on=("role", "organization_member", "member_group", "project"),
    sql="""
CREATE TABLE role_assignment (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id     bigint NOT NULL REFERENCES role (id) ON DELETE CASCADE,
    member_id   bigint REFERENCES organization_member (id) ON DELETE CASCADE,
    group_id    bigint REFERENCES member_group (id) ON DELETE CASCADE,
    project_id  bigint REFERENCES project (id) ON DELETE CASCADE,
    created_at  timestamptz NOT NULL,
    updated_at  timestamptz NOT NULL,
    CONSTRAINT role_assignment_one_of_member_group CHECK ((member_id IS NOT NULL) <> (group_id IS NOT NULL)),
    CONSTRAINT role_assignment_unique UNIQUE NULLS NOT DISTINCT (role_id, member_id, group_id, project_id)
)
""",
)
