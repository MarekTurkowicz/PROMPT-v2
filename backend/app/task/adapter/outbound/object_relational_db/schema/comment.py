from app.shared.adapter.outbound.object_relational_db.schema.objects import Domain, Table

NONEMPTY_TEXT = Domain(name="nonempty_text_d", base="text", check="VALUE <> ''")

COMMENT = Table(
    name="comment",
    depends_on=("task", "project", "organization_member", "nonempty_text_d", "attachment_ids_unique"),
    sql="""
CREATE TABLE comment (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id      bigint REFERENCES task (id) ON DELETE CASCADE,
    project_id   bigint REFERENCES project (id) ON DELETE CASCADE,
    author_id    bigint NOT NULL REFERENCES organization_member (id) ON DELETE RESTRICT,
    parent_id    bigint REFERENCES comment (id) ON DELETE CASCADE,
    content      nonempty_text_d NOT NULL,
    attachments  attachment_d[] NOT NULL,
    created_at   timestamptz NOT NULL,
    updated_at   timestamptz NOT NULL,
    CONSTRAINT comment_one_of_task_project CHECK ((task_id IS NOT NULL) <> (project_id IS NOT NULL)),
    CONSTRAINT comment_attachment_ids_unique CHECK (attachment_ids_unique(attachments))
)
""",
)
