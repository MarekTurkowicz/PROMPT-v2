from app.shared.adapter.outbound.object_relational_db.schema.objects import Domain, Statement, Table

# done_by_id has no FK: an element of an array cannot reference a table.
CHECKLIST_ITEM_TYPE = Statement(
    name="checklist_item_t",
    depends_on=("position_d",),
    sql="""
CREATE TYPE checklist_item_t AS (
    id bigint, checklist_title text, element text, "order" position_d,
    done_by_id bigint, done_at timestamptz, created_at timestamptz, updated_at timestamptz)
""",
)

CHECKLIST_ITEM = Domain(
    name="checklist_item_d",
    base="checklist_item_t",
    depends_on=("checklist_item_t",),
    check="""
    (VALUE).id IS NOT NULL AND (VALUE).element IS NOT NULL
    AND (VALUE)."order" IS NOT NULL AND (VALUE)."order" >= 0
    AND (VALUE).created_at IS NOT NULL AND (VALUE).updated_at IS NOT NULL
    AND ((VALUE).done_by_id IS NULL) = ((VALUE).done_at IS NULL)""",
)

CHECKLIST_IDS_UNIQUE = Statement(
    name="checklist_ids_unique",
    depends_on=("checklist_item_d",),
    sql="""
CREATE FUNCTION checklist_ids_unique(items checklist_item_d[]) RETURNS boolean
LANGUAGE sql IMMUTABLE AS $$
    SELECT count(DISTINCT (items[i]).id) = cardinality(items) FROM generate_subscripts(items, 1) AS i $$
""",
)

TASK = Table(
    name="task",
    depends_on=(
        "project",
        "project_funding",
        "milestone",
        "task_template",
        "task_status",
        "member_group",
        "priority_d",
        "est_hours_d",
        "checklist_ids_unique",
        "attachment_ids_unique",
    ),
    sql="""
CREATE TABLE task (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id          bigint NOT NULL REFERENCES project (id) ON DELETE RESTRICT,
    project_funding_id  bigint REFERENCES project_funding (id) ON DELETE RESTRICT,
    milestone_id        bigint REFERENCES milestone (id) ON DELETE SET NULL,
    parent_id           bigint REFERENCES task (id) ON DELETE CASCADE,
    template_id         bigint REFERENCES task_template (id) ON DELETE SET NULL,
    status_id           bigint NOT NULL REFERENCES task_status (id) ON DELETE RESTRICT,
    group_id            bigint REFERENCES member_group (id) ON DELETE SET NULL,
    title               text NOT NULL,
    description         text NOT NULL,
    priority            priority_d NOT NULL,
    start_date          date,
    due_date            date,
    est_hours           est_hours_d,
    checklist           checklist_item_d[] NOT NULL,
    attachments         attachment_d[] NOT NULL,
    created_at          timestamptz NOT NULL,
    updated_at          timestamptz NOT NULL,
    CONSTRAINT task_dates_ok CHECK (start_date IS NULL OR due_date IS NULL OR due_date >= start_date),
    CONSTRAINT task_checklist_ids_unique CHECK (checklist_ids_unique(checklist)),
    CONSTRAINT task_attachment_ids_unique CHECK (attachment_ids_unique(attachments))
)
""",
)

TASK_TEMPLATE_ONCE_PER_PROJECT_FUNDING = Statement(
    name="task_template_once_per_project_funding",
    depends_on=("task",),
    sql="""
CREATE UNIQUE INDEX task_template_once_per_project_funding ON task (project_funding_id, template_id)
    WHERE project_funding_id IS NOT NULL AND template_id IS NOT NULL
""",
)
