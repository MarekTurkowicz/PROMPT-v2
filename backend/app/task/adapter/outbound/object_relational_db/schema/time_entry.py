from app.shared.adapter.outbound.object_relational_db.schema.objects import Domain, Table

HOURS = Domain(name="hours_d", base="numeric(5,2)", check="VALUE > 0 AND VALUE <> 'NaN'")

# Strict ">" (unlike task_assignment): a time entry of zero length is not work.
TIME_ENTRY = Table(
    name="time_entry",
    depends_on=("task_assignment", "hours_d"),
    sql="""
CREATE TABLE time_entry (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id  bigint NOT NULL REFERENCES task_assignment (id) ON DELETE RESTRICT,
    hours          hours_d NOT NULL,
    started_at     timestamptz NOT NULL,
    finished_at    timestamptz,
    note           text,
    created_at     timestamptz NOT NULL,
    updated_at     timestamptz NOT NULL,
    CONSTRAINT time_entry_dates_ok CHECK (finished_at IS NULL OR finished_at > started_at)
)
""",
)
