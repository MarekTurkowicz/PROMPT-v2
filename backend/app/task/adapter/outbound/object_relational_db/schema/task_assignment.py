from app.shared.adapter.outbound.object_relational_db.schema.objects import Table

TASK_ASSIGNMENT = Table(
    name="task_assignment",
    depends_on=("task", "organization_member"),
    sql="""
CREATE TABLE task_assignment (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id         bigint NOT NULL REFERENCES task (id) ON DELETE CASCADE,
    assigned_to_id  bigint NOT NULL REFERENCES organization_member (id) ON DELETE RESTRICT,
    assigned_by_id  bigint REFERENCES organization_member (id) ON DELETE RESTRICT,
    assigned_at     timestamptz NOT NULL,
    started_at      timestamptz,
    finished_at     timestamptz,
    CONSTRAINT task_assignment_unique UNIQUE (task_id, assigned_to_id),
    CONSTRAINT task_assignment_dates_ok CHECK (
        started_at IS NULL OR finished_at IS NULL OR finished_at >= started_at
    )
)
""",
)
