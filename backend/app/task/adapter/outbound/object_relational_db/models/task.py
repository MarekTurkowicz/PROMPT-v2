from app.shared.adapter.outbound.object_relational_db.objects import Domain, Statement, Table
from app.task.core.domain.constraints.estimated_hours import EstimatedHours
from app.task.core.domain.constraints.priority import Priority

PRIORITY = Domain.from_value_object("priority_d", "smallint", Priority)

EST_HOURS = Domain.from_value_object("est_hours_d", "numeric(6,2)", EstimatedHours)

TASK = Table(
    name="task",
    depends_on=(
        "project",
        "project_funding",
        "milestone",
        "task_template",
        "task_status",
        "member_group",
        "priority_d",
        "est_hours_d",
        "checklist_ids_unique",
        "attachment_ids_unique",
    ),
    sql="""
CREATE TABLE task (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id          bigint NOT NULL REFERENCES project (id) ON DELETE RESTRICT,
    project_funding_id  bigint REFERENCES project_funding (id) ON DELETE RESTRICT,
    milestone_id        bigint REFERENCES milestone (id) ON DELETE SET NULL,
    parent_id           bigint REFERENCES task (id) ON DELETE CASCADE,
    template_id         bigint REFERENCES task_template (id) ON DELETE SET NULL,
    status_id           bigint NOT NULL REFERENCES task_status (id) ON DELETE RESTRICT,
    group_id            bigint REFERENCES member_group (id) ON DELETE SET NULL,
    title               text NOT NULL,
    description         text NOT NULL,
    priority            priority_d NOT NULL,
    start_date          date,
    due_date            date,
    est_hours           est_hours_d,
    checklist           checklist_item_d[] NOT NULL,
    attachments         attachment_d[] NOT NULL,
    created_at          timestamptz NOT NULL,
    updated_at          timestamptz NOT NULL,
    CONSTRAINT task_dates_ok CHECK (start_date IS NULL OR due_date IS NULL OR due_date >= start_date),
    CONSTRAINT task_checklist_ids_unique CHECK (checklist_ids_unique(checklist)),
    CONSTRAINT task_attachment_ids_unique CHECK (attachment_ids_unique(attachments))
)
""",
)

TASK_TEMPLATE_ONCE_PER_PROJECT_FUNDING = Statement(
    name="task_template_once_per_project_funding",
    depends_on=("task",),
    sql="""
CREATE UNIQUE INDEX task_template_once_per_project_funding ON task (project_funding_id, template_id)
    WHERE project_funding_id IS NOT NULL AND template_id IS NOT NULL
""",
)
