from app.shared.adapter.outbound.object_relational_db.objects import Domain, Table
from app.task.core.domain.value_objects.hours import Hours

HOURS = Domain.from_value_object("hours_d", "numeric(5,2)", Hours)

TIME_ENTRY = Table(
    name="time_entry",
    depends_on=("task_assignment", "hours_d"),
    sql="""
CREATE TABLE time_entry (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id  bigint NOT NULL REFERENCES task_assignment (id) ON DELETE RESTRICT,
    hours          hours_d NOT NULL,
    started_at     timestamptz NOT NULL,
    finished_at    timestamptz,
    note           text,
    created_at     timestamptz NOT NULL,
    updated_at     timestamptz NOT NULL,
    CONSTRAINT time_entry_dates_ok CHECK (finished_at IS NULL OR finished_at > started_at)
)
""",
)
